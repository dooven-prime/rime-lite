#!/usr/bin/env python3
"""Start-directed raw 2C macro descent and minimal-trap extraction.

The raw Type-I/Type-II block relation contains no reset-coaccessibility,
Bellman-capacity, or macro-winning predicate.  A failed search therefore
produces the inclusion-minimal forward-closed raw-block set generated by the
start mass.  If that set contains no reset mass, it is an exact hostile witness
against Forced-FFS for the declared automaton.
"""
from __future__ import annotations

from collections import Counter
from typing import Any, Sequence

from costed_endpoint_diagnostic import endpoint_shortest_exits
from mass_maturity_legacy import mass_rank, pushforward_mass, simplified_deadline
from single_defect_transport import (
    fixed_kernel_fusion_data,
    kernel_blocks,
    kernel_occupancy,
    single_defect_alphabet_certificate,
)


Mass = tuple[int, ...]
Letters = tuple[tuple[int, ...], ...]


def _mass_partition(mass: Sequence[int]) -> tuple[int, ...]:
    return tuple(sorted((int(value) for value in mass if value), reverse=True))


def _edge_key(edge: dict[str, Any]) -> tuple[Any, ...]:
    return (
        edge["type"],
        edge["total_length"],
        -edge["total_surplus"],
        tuple(edge["target"]),
        tuple(edge["intermediate"] or ()),
        tuple(edge["first_word"]),
        tuple(edge["second_word"]),
    )


def _raw_type_i(
    source: Mass,
    exits: list[dict[str, Any]],
    n: int,
) -> list[dict[str, Any]]:
    rows = []
    for first in exits:
        surplus = int(first["surplus"])
        if surplus < 0:
            continue
        target = tuple(first["target"])
        rows.append({
            "type": "I",
            "source": list(source),
            "intermediate": None,
            "target": list(target),
            "first_word": list(first["word"]),
            "second_word": [],
            "length_first": int(first["length"]),
            "length_second": 0,
            "total_length": int(first["length"]),
            "surplus_first": surplus,
            "surplus_second": 0,
            "total_surplus": surplus,
            "debt_required": 0,
            "rank_source": mass_rank(source),
            "rank_intermediate": None,
            "rank_target": mass_rank(target),
            "tau_source": simplified_deadline(source, n),
            "tau_target": simplified_deadline(target, n),
        })
    return rows


def _raw_type_ii(
    source: Mass,
    exits: list[dict[str, Any]],
    exits_for: Any,
    n: int,
) -> list[dict[str, Any]]:
    rows = []
    for first in exits:
        surplus_first = int(first["surplus"])
        if surplus_first >= 0:
            continue
        intermediate = tuple(first["target"])
        required = -surplus_first
        for second in exits_for(intermediate):
            surplus_second = int(second["surplus"])
            if surplus_second < required:
                continue
            target = tuple(second["target"])
            rows.append({
                "type": "II",
                "source": list(source),
                "intermediate": list(intermediate),
                "target": list(target),
                "first_word": list(first["word"]),
                "second_word": list(second["word"]),
                "length_first": int(first["length"]),
                "length_second": int(second["length"]),
                "total_length": int(first["length"]) + int(second["length"]),
                "surplus_first": surplus_first,
                "surplus_second": surplus_second,
                "total_surplus": surplus_first + surplus_second,
                "debt_required": required,
                "rank_source": mass_rank(source),
                "rank_intermediate": mass_rank(intermediate),
                "rank_target": mass_rank(target),
                "tau_source": simplified_deadline(source, n),
                "tau_target": simplified_deadline(target, n),
            })
    return rows


def _apply_word(source: Mass, letters: Letters, word: Sequence[int]) -> Mass:
    current = source
    for letter_index in word:
        current = pushforward_mass(current, letters[int(letter_index)])
    return current


def _canonical_occupancy(
    mass: Mass,
    kernel: tuple[tuple[int, ...], ...],
) -> list[dict[str, Any]]:
    rows = []
    for row in kernel_occupancy(mass, kernel):
        masses = sorted((int(value) for value in row["mass"]), reverse=True)
        rows.append({
            "block_size": len(row["block"]),
            "occupied_count": int(row["occupied_count"]),
            "load": sum(masses),
            "masses": masses,
        })
    return sorted(
        rows,
        key=lambda row: (
            row["block_size"],
            row["occupied_count"],
            row["load"],
            row["masses"],
        ),
    )


def corridor_structural_profile(
    source: Mass,
    word: Sequence[int],
    letters: Letters,
    defect_index: int,
) -> dict[str, Any]:
    """Describe one endpoint-shortest strict corridor without future labels."""
    if not word or int(word[-1]) != defect_index:
        raise AssertionError("strict single-defect corridor must end in d")
    n = len(source)
    defect = letters[defect_index]
    boundary = _apply_word(source, letters, word[:-1])
    target = pushforward_mass(boundary, defect)
    fusion = fixed_kernel_fusion_data(boundary, defect)
    kernel = kernel_blocks(defect, n)
    length = len(word)
    credit = simplified_deadline(target, n) - simplified_deadline(source, n)
    surplus = credit - length
    return {
        "source": list(source),
        "source_rank": mass_rank(source),
        "source_partition": list(_mass_partition(source)),
        "source_occupancy": _canonical_occupancy(source, kernel),
        "boundary": list(boundary),
        "boundary_partition": list(_mass_partition(boundary)),
        "boundary_occupancy": _canonical_occupancy(boundary, kernel),
        "target": list(target),
        "target_rank": mass_rank(target),
        "target_partition": list(_mass_partition(target)),
        "word": [int(value) for value in word],
        "endpoint_distance": length,
        "transport_distance": length - 1,
        "q_d": int(fusion["q_d"]),
        "delta_m_d": int(fusion["delta_m_d"]),
        "credit": credit,
        "surplus": surplus,
    }


def type_ii_structural_profile(
    edge: dict[str, Any],
    letters: Letters,
    defect_index: int,
) -> dict[str, Any]:
    if edge["type"] != "II":
        raise ValueError("Type-II structural profile requires a Type-II edge")
    source = tuple(edge["source"])
    intermediate = tuple(edge["intermediate"])
    first = corridor_structural_profile(
        source, edge["first_word"], letters, defect_index
    )
    second = corridor_structural_profile(
        intermediate, edge["second_word"], letters, defect_index
    )
    return {
        "source": list(source),
        "source_partition": list(_mass_partition(source)),
        "intermediate": list(intermediate),
        "intermediate_partition": list(_mass_partition(intermediate)),
        "target": list(edge["target"]),
        "target_partition": list(_mass_partition(edge["target"])),
        "debt_required": int(edge["debt_required"]),
        "combined_surplus": int(edge["total_surplus"]),
        "first": first,
        "second": second,
    }


def analyze_raw_macro_descent(
    letters: Letters,
    n: int,
    *,
    start_mass: Mass | None = None,
) -> dict[str, Any]:
    """Find a raw macro descent or serialize its generated minimal trap."""
    frozen = tuple(tuple(letter) for letter in letters)
    certificate = single_defect_alphabet_certificate(frozen, n)
    defect_index = int(certificate["defect_index"])
    defect = frozen[defect_index]
    start = (
        tuple(start_mass)
        if start_mass is not None
        else pushforward_mass((1,) * n, defect)
    )

    exit_cache: dict[Mass, list[dict[str, Any]]] = {}
    block_cache: dict[Mass, list[dict[str, Any]]] = {}
    winning: dict[Mass, bool] = {}
    choice: dict[Mass, dict[str, Any]] = {}
    evaluated = Counter()

    def exits_for(mass: Mass) -> list[dict[str, Any]]:
        if mass not in exit_cache:
            exit_cache[mass] = endpoint_shortest_exits(mass, frozen, n)
            evaluated["endpoint_tables"] += 1
        return exit_cache[mass]

    def blocks_for(mass: Mass) -> list[dict[str, Any]]:
        if mass in block_cache:
            return block_cache[mass]
        if mass_rank(mass) == 1:
            block_cache[mass] = []
            return []
        exits = exits_for(mass)
        rows = _raw_type_i(mass, exits, n)
        rows.extend(_raw_type_ii(mass, exits, exits_for, n))
        for row in rows:
            if row["rank_target"] >= row["rank_source"]:
                raise AssertionError("raw macro block did not lower rank")
            if row["type"] == "II" and (
                row["rank_intermediate"] >= row["rank_source"]
                or row["rank_target"] >= row["rank_intermediate"]
            ):
                raise AssertionError("Type-II component did not lower rank")
            expected = (
                simplified_deadline(tuple(row["target"]), n)
                - simplified_deadline(mass, n)
                - row["total_length"]
            )
            if row["total_surplus"] != expected:
                raise AssertionError("raw macro surplus did not telescope")
        block_cache[mass] = sorted(rows, key=_edge_key)
        evaluated["raw_blocks"] += len(rows)
        return block_cache[mass]

    def solve(mass: Mass) -> bool:
        if mass in winning:
            return winning[mass]
        if mass_rank(mass) == 1:
            winning[mass] = True
            return True
        for edge in blocks_for(mass):
            target = tuple(edge["target"])
            if solve(target):
                winning[mass] = True
                choice[mass] = edge
                return True
        winning[mass] = False
        return False

    found = solve(start)
    if found:
        steps = []
        current = start
        while mass_rank(current) > 1:
            edge = choice[current]
            steps.append(edge)
            current = tuple(edge["target"])
        type_ii_profiles = [
            type_ii_structural_profile(edge, frozen, defect_index)
            for edge in steps
            if edge["type"] == "II"
        ]
        return {
            "found": True,
            "start_mass": list(start),
            "start_rank": mass_rank(start),
            "terminal_mass": list(current),
            "macro_step_count": len(steps),
            "corridor_count": sum(1 if row["type"] == "I" else 2 for row in steps),
            "total_length": sum(int(row["total_length"]) for row in steps),
            "total_surplus": sum(int(row["total_surplus"]) for row in steps),
            "witness_types": [row["type"] for row in steps],
            "steps": steps,
            "type_ii_profiles": type_ii_profiles,
            "states_solved": len(winning),
            "endpoint_tables_evaluated": evaluated["endpoint_tables"],
            "raw_blocks_evaluated": evaluated["raw_blocks"],
            "minimal_raw_macro_trap": None,
        }

    closure = {start}
    queue = [start]
    while queue:
        current = queue.pop()
        for edge in blocks_for(current):
            target = tuple(edge["target"])
            if target not in closure:
                closure.add(target)
                queue.append(target)
    if any(mass_rank(mass) == 1 for mass in closure):
        raise AssertionError("failed search generated a trap containing reset")
    trap_rows = []
    for mass in sorted(closure, key=lambda value: (mass_rank(value), value)):
        blocks = blocks_for(mass)
        outside = [row for row in blocks if tuple(row["target"]) not in closure]
        if outside:
            raise AssertionError("generated raw macro trap is not forward closed")
        trap_rows.append({
            "mass": list(mass),
            "rank": mass_rank(mass),
            "partition": list(_mass_partition(mass)),
            "outgoing_blocks": blocks,
        })
    rank_counts = Counter(str(mass_rank(mass)) for mass in closure)
    trap = {
        "minimality": "forward-reachability closure generated by start_mass",
        "start_mass": list(start),
        "state_count": len(closure),
        "rank_counts": dict(sorted(rank_counts.items())),
        "contains_reset": False,
        "forward_closed": True,
        "states": trap_rows,
    }
    return {
        "found": False,
        "start_mass": list(start),
        "start_rank": mass_rank(start),
        "terminal_mass": None,
        "macro_step_count": None,
        "corridor_count": None,
        "total_length": None,
        "total_surplus": None,
        "witness_types": [],
        "steps": [],
        "type_ii_profiles": [],
        "states_solved": len(winning),
        "endpoint_tables_evaluated": evaluated["endpoint_tables"],
        "raw_blocks_evaluated": evaluated["raw_blocks"],
        "minimal_raw_macro_trap": trap,
    }


__all__ = [
    "analyze_raw_macro_descent",
    "corridor_structural_profile",
    "type_ii_structural_profile",
]
