"""Supp_nc — Noncommutativity localization in the representation.

Computationally verified:
  - cp block: exactly commutative ([QT⁰, QT¹] = 0 identically)
  - ep block: carries >93% of total noncommutativity
  - co, eo blocks: residual noncommutativity (<25% each)
  - Noncommutativity is generated by face-incidence in EP block

Paper: Paper II, Sec 5 (Commutant & Noncommutativity)
Invariant level: 2 (generator-conditioned)
"""
import numpy as np
import os
from rime.cubieoperator import CubieSpectralOperator
from rime.cubie import CubieMove, BLOCK_RANGES, TOTAL_DIM
TOL = 1e-10
FIG_DIR = os.path.join(os.path.dirname(__file__), '..', '..', 'figures', 'paper2')
os.makedirs(FIG_DIR, exist_ok=True)

op = CubieSpectralOperator.from_gens_dict(CubieMove.prim_moves)
center = op.build_per_axis_ops()[0]
QT0 = center['QT0']
QT1 = center['QT1']
A = op.A
QT_all = center['QT_all']
HT_all = center['HT_all']

print("=" * 60)
print("  Paper II — Noncommutativity Localization (Supp_nc)")
print("=" * 60)

# 1. Center commutativity
c_ah = np.linalg.norm(A @ HT_all - HT_all @ A, 'fro')
c_aq = np.linalg.norm(A @ QT_all - QT_all @ A, 'fro')
c_qh = np.linalg.norm(QT_all @ HT_all - HT_all @ QT_all, 'fro')
print(f"\n  1. Center commutativity:")
print(f"     [A, QT_all] = {c_aq:.2e}")
print(f"     [A, HT_all] = {c_ah:.2e}")
print(f"     [QT_all, HT_all] = {c_qh:.2e}")
assert max(c_ah, c_aq, c_qh) < TOL, "Center non-commutative!"

# 2. Total noncommutativity
comm = QT0 @ QT1 - QT1 @ QT0
total_nc = np.linalg.norm(comm, 'fro')
print(f"\n  2. Total ||[QT⁰, QT¹]||_F = {total_nc:.4f}")

# 3. Per-block noncommutativity
print(f"\n  3. Per-block noncommutativity:")
block_nc = {}
for bn, (start, end) in BLOCK_RANGES.items():
    d = end - start
    nc = np.linalg.norm(comm[start:end, start:end], 'fro')
    pct = 100 * nc / total_nc
    block_nc[bn] = nc
    print(f"     {bn}({d}d): ||[QT⁰,QT¹]|| = {nc:.4f}  ({pct:.1f}% of total)")

# cp must be commutative
assert block_nc['cp'] < TOL, f"cp block should be commutative: {block_nc['cp']:.2e}"
print(f"\n  cp block commutative: ✓")
# ep must carry >90%
ep_pct = 100 * block_nc['ep'] / total_nc
assert ep_pct > 90, f"ep should carry >90% noncommutativity: {ep_pct:.1f}%"
print(f"  ep block dominant ({ep_pct:.1f}%): ✓")

# ── Figure ──
try:
    import matplotlib
    matplotlib.use('Agg')
    import matplotlib.pyplot as plt

    fig, (ax1, ax2) = plt.subplots(1, 2, figsize=(14, 5))

    # Bar chart
    block_names = list(BLOCK_RANGES.keys())
    block_dims = [end - start for _, (start, end) in BLOCK_RANGES.items()]
    nc_vals = [block_nc[bn] for bn in block_names]
    colors = ['#5b6abf', '#e74c3c', '#f39c12', '#16a085']

    ax1.bar(block_names, nc_vals, color=colors, edgecolor='white', linewidth=1.5)
    ax1.set_ylabel('||[QT⁰, QT¹]||_F')
    ax1.set_title('Noncommutativity by Block')
    for i, v in enumerate(nc_vals):
        ax1.text(i, v + 0.05, f'{v:.2f}', ha='center', fontsize=10)

    # Commutator matrix heatmap
    comm_abs = np.abs(comm)
    im = ax2.imshow(comm_abs, cmap='YlOrRd', aspect='auto', vmin=0)
    # Block boundaries (from BLOCK_RANGES)
    boundaries = [v[0] for v in BLOCK_RANGES.values()] + [TOTAL_DIM]
    for b in boundaries:
        ax2.axhline(y=b-0.5, color='white', linewidth=1, linestyle='--', alpha=0.5)
        ax2.axvline(x=b-0.5, color='white', linewidth=1, linestyle='--', alpha=0.5)
    # Block labels
    for i, (bn, (s, e)) in enumerate(BLOCK_RANGES.items()):
        ax2.text((s+e)/2 - 0.5, -5, bn, ha='center', fontsize=9, fontweight='bold')
        ax2.text(-5, (s+e)/2 - 0.5, bn, ha='center', fontsize=9, fontweight='bold',
                rotation=90, va='center')
    ax2.set_title('|[QT⁰, QT¹]| Heatmap')
    plt.colorbar(im, ax=ax2, shrink=0.8)

    plt.tight_layout()
    fig.savefig(os.path.join(FIG_DIR, 'supp_nc.png'), dpi=150, bbox_inches='tight')
    plt.close()
    print(f"\n  Figure saved: {os.path.join(FIG_DIR, 'supp_nc.png')}")
except ImportError:
    pass

print(f"\nDone — Supp_nc verified: cp=0, ep={ep_pct:.1f}% of noncommutativity.")
